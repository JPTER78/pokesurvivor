#!/usr/bin/env python3
"""Subset Noto Sans SC for offline UI. Build-only: fonttools and brotli."""
import hashlib
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools/cache/python'))
from fontTools import subset
from fontTools.ttLib import TTFont

inputs = [ROOT/'dev.html', ROOT/'contacto/index.html', ROOT/'manifest.webmanifest', ROOT/'tools/seo_zh.py', ROOT/'tools/make_seo_pages.py', *sorted((ROOT/'js').rglob('*.js'))]
text = ''.join(p.read_text(encoding='utf-8') for p in inputs if p.name != 'app.min.js')
chars = {ord(c) for c in text if ord(c) >= 0x2e80}
faces = []; manifest = {'source':'Noto Sans SC / notofonts/noto-cjk', 'characters':len(chars), 'fonts':[]}
for weight,label in [(400,'Regular'),(700,'Bold')]:
    font = TTFont(ROOT/f'tools/cache/localization/NotoSansSC-{label}.otf', recalcTimestamp=False)
    missing = chars - set(font.getBestCmap())
    missing_han = {u for u in missing if 0x3400 <= u <= 0x9fff or 0x20000 <= u <= 0x2fa1f}
    if missing_han: raise ValueError('Missing CJK glyphs: '+str(sorted(missing_han)))
    options = subset.Options(); options.flavor = 'woff2'
    options.name_IDs = ['*']; options.name_legacy = True; options.name_languages = ['*']
    sub = subset.Subsetter(options=options); sub.populate(unicodes=chars-missing); sub.subset(font)
    for name in font['name'].names:
        if name.nameID in (1,4,6,16):
            value = 'PSChinese-'+label if name.nameID == 6 else 'PSChinese'
            name.string = value.encode(name.getEncoding())
    font.flavor = 'woff2'
    dest = ROOT/f'tools/cache/localization/PSChinese-{weight}.woff2'; font.save(dest)
    data = dest.read_bytes(); digest = hashlib.sha256(data).hexdigest()
    filename = f'PSChinese-{weight}-{digest[:10]}.woff2'
    (ROOT/'assets/fonts'/filename).write_bytes(data)
    manifest['fonts'].append({'weight':weight,'file':filename,'sha256':digest,'bytes':len(data)})
    span = '400 550' if weight == 400 else '551 900'
    faces.append(f"@font-face {{ font-family: 'PSChinese'; src: url('../assets/fonts/{filename}') format('woff2'); font-weight: {span}; font-display: swap; }}")
(ROOT/'assets/fonts/NotoSansSC-OFL.txt').write_text((ROOT/'tools/cache/localization/Noto-OFL.txt').read_text(encoding='utf-8'),encoding='utf-8')
(ROOT/'css/fonts-zh.css').write_text('/* Generated by tools/make_zh_font.py; local Noto Sans SC subset (OFL-1.1). */\n'+'\n'.join(faces)+'\n',encoding='utf-8')
(ROOT/'tools/localization/font-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps(manifest,ensure_ascii=False))

